// The skills surface: one SKILL.md per block noun, generated from catalog metadata only, next to
// the generated CLI and MCP surfaces. The lint (D9) keeps any skill honest against the catalog.
import {
  isAgentCallable,
  renamedOperation,
  type McpCandidate,
} from "../contract/mcp.ts";
import {
  CORE_NOUNS,
  cliWords,
  mcpToolName,
  parseOperationName,
} from "../contract/naming.ts";
import { record } from "./dispatch.ts";
import { discoveryOperations } from "./discovery.ts";

/** D9 ceiling: a skill larger than this fails the lint. */
export const SKILL_MAX_BYTES = 8192;
/** Harnesses truncate or reject longer skill descriptions. */
export const SKILL_DESCRIPTION_MAX = 1024;

/**
 * Marks a file as written by skills.sync: sync overwrites files with this exact line, deletes
 * them when it no longer produces them, and never touches unmarked skill folders.
 */
export const GENERATED_MARKER =
  "<!-- Generated by forge skills sync from the catalog; edits are overwritten. -->";

export interface SkillFile {
  readonly noun: string;
  /** Relative to the skills directory, "/"-separated. */
  readonly path: string;
  readonly text: string;
}

/** Display only: a field's declared type, or "see schema" when it is a `$ref`, `anyOf` or the like. */
function typeOf(schema: unknown): string {
  const s = record(schema);
  if (Array.isArray(s?.enum))
    return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s?.type === "array" && typeof record(s.items)?.type === "string")
    return `${String(record(s.items)?.type)}[]`;
  if (typeof s?.type === "string") return s.type;
  return Array.isArray(s?.type) ? s.type.join(" | ") : "see schema";
}

/** Top-level input fields with required or optional; the full schema stays one `catalog describe` away. */
function fields(schema: Readonly<Record<string, unknown>>): string {
  const properties = record(schema.properties);
  if (properties === undefined) return typeOf(schema);
  const required = Array.isArray(schema.required) ? schema.required : [];
  const listed = Object.entries(properties).map(
    ([key, value]) =>
      `\`${key}\` ${typeOf(value)} (${required.includes(key) ? "required" : "optional"})`,
  );
  return listed.length === 0 ? "none" : listed.join(", ");
}

function section(candidate: McpCandidate, prefix: string | undefined): string {
  const { op, declaration, docs } = candidate;
  const effects =
    declaration.effects.length === 0
      ? "none (read-only)"
      : declaration.effects.map((e) => `\`${e}\``).join(", ");
  const declared = declaration.deprecated?.use;
  const deprecated =
    declared === undefined
      ? undefined
      : renamedOperation(declared, candidate.rename);
  return [
    `## \`${op}\` — ${docs.title}`,
    "",
    ...(deprecated === undefined ? [] : [`Deprecated: use \`${deprecated}\`.`]),
    docs.summary,
    "",
    `- CLI: \`forge ${(cliWords(op) ?? [op]).join(" ")} --input '<json>'\``,
    `- MCP: \`${mcpToolName(op, prefix) ?? "catalog_call"}\``,
    `- Input: ${fields(candidate.argumentSchema ?? candidate.inputSchema)}`,
    `- Effects: ${effects}; ${declaration.idempotent ? "idempotent" : "not idempotent"}`,
    "",
  ].join("\n");
}

function describe(noun: string, agent: readonly McpCandidate[]): string {
  const verbs = agent.map((c) => parseOperationName(c.op)?.verb).join(", ");
  let text = `Forge ${noun} operations (${verbs}), callable from the CLI or MCP.`;
  for (const candidate of agent) {
    const next = `${text} ${candidate.docs.summary}`;
    if (next.length > SKILL_DESCRIPTION_MAX) break;
    text = next;
  }
  return text.replace(/\s+/g, " ");
}

function skill(
  noun: string,
  entries: readonly McpCandidate[],
  prefix: string | undefined,
): string {
  const agent = entries.filter((c) => isAgentCallable(c.declaration));
  const human = entries.filter((c) => !isAgentCallable(c.declaration));
  return [
    "---",
    `name: ${noun}`,
    `description: ${JSON.stringify(describe(noun, agent))}`,
    "---",
    "",
    `# ${noun}`,
    "",
    GENERATED_MARKER,
    "Every call returns a JSON result envelope. When an MCP tool below is not listed, use `catalog_call` with the operation name and input; `catalog_describe` returns the full schemas.",
    "",
    ...agent.map((c) => section(c, prefix)),
    ...(human.length === 0
      ? []
      : [
          "## Human only",
          "",
          "Agents cannot call these; ask a person to run them:",
          "",
          ...human.map((c) => `- \`${c.op}\`: ${c.docs.summary}`),
          "",
        ]),
  ].join("\n");
}

/**
 * One skill per block noun with at least one admitted, agent-callable operation; sorted, so output
 * is stable. Unadmitted operations are dropped first, as every other discovery surface hides them.
 */
export function renderSkills(
  candidates: readonly McpCandidate[],
  prefix?: string,
): readonly SkillFile[] {
  const byNoun = new Map<string, McpCandidate[]>();
  for (const candidate of [...candidates].sort((a, b) =>
    a.op < b.op ? -1 : a.op > b.op ? 1 : 0,
  )) {
    if (!candidate.admitted) continue;
    const noun = parseOperationName(candidate.op)?.noun;
    if (noun === undefined || CORE_NOUNS.includes(noun)) continue;
    byNoun.set(noun, [...(byNoun.get(noun) ?? []), candidate]);
  }
  return [...byNoun]
    .filter(([, entries]) =>
      entries.some((c) => isAgentCallable(c.declaration)),
    )
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([noun, entries]) => ({
      noun,
      path: `${noun}/SKILL.md`,
      text: skill(noun, entries, prefix),
    }));
}

const scalar = (value: unknown): value is string | number | boolean =>
  ["string", "number", "boolean"].includes(typeof value);

/**
 * A template's hand-written skill with each `{{values.<path>}}` replaced by the project's effective
 * value, and the generated marker placed after the frontmatter. Returns the placeholders it could
 * not resolve instead when there are any.
 */
export function renderTemplateSkill(
  name: string,
  source: string,
  values: unknown,
): SkillFile | { readonly unknown: readonly string[] } {
  const unknown: string[] = [];
  const text = source
    .replace(/\r\n/g, "\n")
    .replace(/\{\{\s*([^{}]*?)\s*\}\}/g, (whole, key: string) => {
      let value: unknown = /^values(?:\.[^.\s]+)+$/.test(key)
        ? values
        : undefined;
      for (const part of key.split(".").slice(1)) value = record(value)?.[part];
      // a scalar or a list of scalars; an object has no one text form
      if (scalar(value)) return String(value);
      if (Array.isArray(value) && value.every(scalar)) return value.join(", ");
      unknown.push(whole);
      return whole;
    });
  if (unknown.length > 0) return { unknown };
  const front = /^---\n[\s\S]*?\n---\n/.exec(text)?.[0] ?? "";
  return {
    noun: name,
    path: `${name}/SKILL.md`,
    text: `${front}${GENERATED_MARKER}\n${text.slice(front.length)}`,
  };
}

const NAME = "[a-z][a-z0-9-]*";
const CLI_FORM = new RegExp(`^forge (${NAME}) (${NAME})(?:\\s|$)`);
const OP_FORM = new RegExp(`^(${NAME})[._](${NAME})$`);
const MODEL_LITERAL =
  "(?<![\\w-])(?:gpt-\\d[a-z0-9._-]*|claude-(?:opus|sonnet|haiku|fable|\\d)[a-z0-9._-]*|gemini-\\d[a-z0-9._-]*|deepseek-[a-z0-9][a-z0-9._-]*|o\\d|opus|sonnet|haiku)(?![\\w-])";
const EFFORT_LEVEL = "(?:minimal|low|medium|high|xhigh|max)(?![\\w-])";
const ROUTING_LITERAL =
  `(?<![\\w-])(?:--model(?:[ \\t]*=[ \\t]*|[ \\t]+)|-m[ \\t]+)["'\x60]?${MODEL_LITERAL}["'\x60]?` +
  `|(?<![\\w-])(?:--effort(?:[ \\t]*=[ \\t]*|[ \\t]+)|["']?(?:model_reasoning_effort|reasoning_effort|reasoning|effort)["']?[ \\t]*[:=][ \\t]*|reasoning[ \\t]+)["'\x60]?${EFFORT_LEVEL}["'\x60]?`;

/**
 * D9: a skill must fit the size ceiling, carry a name and description, avoid literal model/effort
 * choices, and name only catalog operations. Operations are read from code spans: `noun.verb`, `noun_verb` and
 * `forge noun verb`; a dotted or underscored span counts only when its noun is a catalog noun.
 */
export function lintSkill(
  text: string,
  candidates: readonly McpCandidate[],
  prefix?: string,
  maxBytes: number = SKILL_MAX_BYTES,
): readonly string[] {
  const problems: string[] = [];
  const bytes = new TextEncoder().encode(text).length;
  if (bytes > maxBytes)
    problems.push(`skill is ${bytes} bytes; the limit is ${maxBytes}`);
  const front = /^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "";
  if (!/^name: \S/m.test(front)) problems.push("frontmatter has no name");
  const description = /^description: (.*)$/m.exec(front)?.[1];
  if (description === undefined)
    problems.push("frontmatter has no description");
  else if (description.length > SKILL_DESCRIPTION_MAX + 2)
    problems.push(`description exceeds ${SKILL_DESCRIPTION_MAX} characters`);
  const concrete = text.replace(/<(?!!--)[^<>\n]*>|\{[^{}\n:"']*\}/g, (span) =>
    "\0".repeat(span.length),
  );
  const routing = new RegExp(`${ROUTING_LITERAL}|${MODEL_LITERAL}`, "gi");
  for (const match of concrete.matchAll(routing)) {
    const line = text.slice(0, match.index).split("\n").length;
    const span = text.slice(match.index, match.index + match[0].length);
    problems.push(`literal model or effort in \`${span}\` on line ${line}`);
  }
  const known = new Set(
    [...discoveryOperations, ...candidates].map((c) => c.op),
  );
  const nouns = new Set(
    [...known].map((op) => parseOperationName(op)?.noun ?? op),
  );
  for (const [, span = ""] of text.matchAll(/`([^`\n]+)`/g)) {
    const bare =
      prefix !== undefined && span.startsWith(`${prefix}_`)
        ? span.slice(prefix.length + 1)
        : span;
    const cli = CLI_FORM.exec(span);
    const named = cli ?? OP_FORM.exec(bare);
    if (named === null) continue;
    const op = `${named[1]}.${named[2]}`;
    if (!known.has(op) && (cli !== null || nouns.has(named[1] ?? "")))
      problems.push(`unknown operation ${op} in \`${span}\``);
  }
  return problems;
}
