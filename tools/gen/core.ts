import { join } from "node:path";
import { assembleCoreManifest } from "../../src/core/catalog/index.ts";
import { operations as catalog } from "../../src/core/catalog/operations.ts";
import { operations as trust } from "../../src/core/trust/operations.ts";
import { repoRoot } from "./types.ts";
import { writeGenerated } from "./write.ts";

/** Inline file references so advertised schemas need no repository-relative resolver. */
function readSchema(url: URL): unknown {
  const expand = (node: unknown): unknown => {
    if (Array.isArray(node)) return node.map(expand);
    if (node === null || typeof node !== "object") return node;
    const object = node as Record<string, unknown>;
    if (
      typeof object.$ref === "string" &&
      !object.$ref.includes(":") &&
      !object.$ref.startsWith("#")
    ) {
      return {
        ...(readSchema(new URL(object.$ref, url)) as object),
        ...Object.fromEntries(
          Object.entries(object)
            .filter(([key]) => key !== "$ref")
            .map(([key, value]) => [key, expand(value)]),
        ),
      };
    }
    return Object.fromEntries(
      Object.entries(object).map(([key, value]) => [key, expand(value)]),
    );
  };
  return expand(JSON.parse(readFileSync(url, "utf8")) as unknown);
}

/** Each area owns its typed declarations; this is the sole assembly boundary. */
export function writeCoreManifest(root: string = repoRoot): void {
  const manifest = assembleCoreManifest(
    {
      schemaVersion: "forge.block/1",
      id: "forge/core",
      version: "1.0.0",
      authorAbi: "forge.author/v2",
      profile: "trusted-action/v2",
      entry: "index.cjs",
      docs: "docs.json",
    },
    [catalog, trust],
  );
  const directory = join(root, "src/generated");
  const docs = JSON.parse(
    readFileSync(
      new URL("../../src/assembly/docs.json", import.meta.url),
      "utf8",
    ),
  ) as { operations: Record<string, unknown> };
  const candidates = Object.entries(manifest.operations).map(
    ([op, declaration]) => ({
      op,
      admitted: true,
      declaration,
      docs: docs.operations[op] ?? { title: op, summary: `Run ${op}.` },
      inputSchema: JSON.parse(
        readFileSync(
          new URL(`../../src/core/${declaration.input}`, import.meta.url),
          "utf8",
        ),
      ) as unknown,
      outputSchema: readSchema(
        new URL(`../../src/core/${declaration.output}`, import.meta.url),
      ),
    }),
  );
  writeGenerated(
    join(directory, "core-discovery.ts"),
    "// Generated by tools/gen/core.ts from area-owned declarations. Do not edit.\n" +
      'import type { McpCandidate } from "../contract/mcp.ts";\n' +
      `export const discoveryOperations: readonly McpCandidate[] = ${JSON.stringify(candidates, null, 2)};\n`,
  );
  writeGenerated(
    join(directory, "core-manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
}
