'use strict';

// Forge-owned generator for .github/workflows/size-check.yml, following the
// `forge release generate-npm-workflow` pattern: a deterministic renderer
// (input: the staged package.json Bun pin only),
// an exact-bytes Kernel capability that is issued, written, audited, and
// completed, and a protected-state check that accepts only those bytes.

const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const {
	createProtectedStateAuditRecord,
	recordProtectedStateAuditEvent,
	removeProtectedFile,
	writeProtectedFile,
} = require('./protected-state-surfaces');
const {
	readIndexedPackageManifest,
	readPinnedBunVersion,
	resolveCurrentHead,
} = require('./bun-workflow-pins');
const { readGitFile } = require('./test-workflow');

const SIZE_WORKFLOW_PATH = '.github/workflows/size-check.yml';

/**
 * Renders size-check.yml as exact bytes. Its only input is the Bun version:
 * no manifest, timestamps, env, or filesystem reads. The workflow has no path
 * filters, so a new publishable path can never escape the check, and this
 * renderer is the single source of truth for the file's bytes (update-bun-pins
 * delegates to it rather than editing the pin line).
 *
 * @param {string} bunVersion exact stable Bun version from package.json packageManager
 * @returns {Buffer}
 */
function renderSizeWorkflow(bunVersion) {
	if (!/^\d+\.\d+\.\d+$/.test(bunVersion)) {
		throw new Error('Size workflow requires an exact stable Bun version.');
	}
	return Buffer.from(`# Generated by \`forge release generate-size-workflow\` from lib/size-workflow.js.
# Do not edit by hand: change the renderer and regenerate.
name: Package Size Monitor

on:
  push:
    branches: [main, master]
  pull_request:
    branches: [main, master]

concurrency:
  group: size-check-\${{ github.event.pull_request.number || github.ref }}
  cancel-in-progress: true

jobs:
  size-check:
    name: Check Package Size
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: read

    steps:
      # On pull_request the checkout is the merge commit; depth 2 brings in its
      # first parent, the exact base revision this run measures against.
      - name: Checkout code
        uses: actions/checkout@v7
        with:
          fetch-depth: \${{ github.event_name == 'pull_request' && 2 || 1 }}

      - name: Setup Bun
        uses: oven-sh/setup-bun@v2
        with:
          bun-version: ${bunVersion}

      # npm pack only includes bundledDependencies that exist in node_modules.
      - name: Install dependencies
        run: bun install --frozen-lockfile --ignore-scripts

      - name: Read the base baseline from the merge commit parent
        if: github.event_name == 'pull_request'
        run: |
          git show HEAD^1:scripts/package-size-baseline.json > "$RUNNER_TEMP/base-baseline.json" || rm -f "$RUNNER_TEMP/base-baseline.json"

      - name: Check package size budgets
        run: node scripts/package-size-check.js --previous "$RUNNER_TEMP/base-baseline.json"
`);
}

function readIndexedSizeWorkflow(projectRoot, execGit) {
	return readGitFile(projectRoot, ':', SIZE_WORKFLOW_PATH, execGit);
}

function readRegularFile(projectRoot, filePath) {
	const fullPath = path.join(projectRoot, filePath);
	const stat = fs.lstatSync(fullPath);
	if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`${filePath} must be a regular file.`);
	return fs.readFileSync(fullPath);
}

function snapshotWorkflow(projectRoot) {
	try {
		return { existed: true, content: readRegularFile(projectRoot, SIZE_WORKFLOW_PATH) };
	} catch (error) {
		if (error.code === 'ENOENT') return { existed: false, content: null };
		throw error;
	}
}

/**
 * Resolves the exact size workflow update after checking HEAD and that the
 * staged package.json matches the working tree. The committed
 * workflow at HEAD is the baseline; the working and staged workflow must each
 * be either that baseline or the generated bytes, so unrelated edits are
 * never overwritten.
 */
function resolveSizeWorkflowUpdate(projectRoot, sourceHead, options = {}) {
	const currentHead = (options.resolveHead || resolveCurrentHead)(projectRoot, options.execGit);
	if (currentHead !== sourceHead) {
		throw new Error(`Protected size workflow source HEAD changed from ${sourceHead} to ${currentHead}.`);
	}
	const readGit = options.readGitFile || readGitFile;
	const indexedPackage = Buffer.from((options.readIndexedPackageManifest || readIndexedPackageManifest)(projectRoot, options.execGit));
	if (!readRegularFile(projectRoot, 'package.json').equals(indexedPackage)) {
		throw new Error(`package.json differs from the Git index; stage the intended manifest before generating ${SIZE_WORKFLOW_PATH}.`);
	}
	const version = readPinnedBunVersion(indexedPackage);
	const content = renderSizeWorkflow(version);
	const baseline = Buffer.from(readGit(projectRoot, sourceHead, SIZE_WORKFLOW_PATH, options.execGit));
	const snapshot = snapshotWorkflow(projectRoot);
	if (!snapshot.existed || (!snapshot.content.equals(baseline) && !snapshot.content.equals(content))) {
		throw new Error(`${SIZE_WORKFLOW_PATH} has unrelated local edits; restore or commit them before generation.`);
	}
	const indexedWorkflow = Buffer.from(readGit(projectRoot, ':', SIZE_WORKFLOW_PATH, options.execGit));
	if (!indexedWorkflow.equals(baseline) && !indexedWorkflow.equals(content)) {
		throw new Error(`${SIZE_WORKFLOW_PATH} has unrelated staged edits; restore or commit them before generation.`);
	}
	return { path: SIZE_WORKFLOW_PATH, sourceHead, version, baseline, content, indexedWorkflow, snapshot };
}

function sameSnapshot(left, right) {
	return left?.existed === right?.existed
		&& (!left?.existed || (Buffer.isBuffer(left.content) && left.content.equals(right.content)));
}

// Binds a generation inside update-bun-pins to the bytes its preflight resolved.
function matchesExpectedUpdate(expectedUpdate, update) {
	if (!expectedUpdate) return true;
	try {
		return expectedUpdate.version === update.version && Buffer.from(expectedUpdate.content).equals(update.content);
	} catch {
		return false;
	}
}

function attemptRecovery(snapshot, projectRoot, generatedContent, protectedWriter, protectedRemover, writeOptions) {
	const recoveryOptions = { ...writeOptions, operation: 'recover_size_workflow', expectedContent: generatedContent };
	try {
		return snapshot.existed
			? protectedWriter(projectRoot, SIZE_WORKFLOW_PATH, snapshot.content, recoveryOptions)
			: protectedRemover(projectRoot, SIZE_WORKFLOW_PATH, recoveryOptions);
	} catch (error) {
		return { allowed: false, reason: error.message };
	}
}

/**
 * Generates size-check.yml: verify HEAD, resolve exact bytes, issue a Kernel
 * capability, write atomically, audit, and complete. Audit or completion
 * failures restore the prior snapshot.
 */
async function generateSizeWorkflow(projectRoot, options = {}) {
	const { verifyExpectedHead } = require('./npm-publish-workflow');
	const head = verifyExpectedHead(projectRoot, options.expectedHead, options.resolveHead);
	if (!head.success) return head;
	const sourceHead = head.sourceHead;
	if (options.expectedSnapshot && !sameSnapshot(options.expectedSnapshot, snapshotWorkflow(projectRoot))) {
		return { success: false, error: `${SIZE_WORKFLOW_PATH} changed after Bun pin batch preflight.` };
	}
	let update;
	try {
		update = resolveSizeWorkflowUpdate(projectRoot, sourceHead, options);
	} catch (error) {
		return { success: false, error: error.message };
	}
	if (!matchesExpectedUpdate(options.expectedUpdate, update)) {
		return { success: false, error: `${SIZE_WORKFLOW_PATH} changed after Bun pin batch preflight.` };
	}

	const authority = require('./protected-state-authority');
	const env = options.env || process.env;
	const actor = options.actor || env.FORGE_PROTECTED_STATE_ACTOR || env.FORGE_ACTOR || env.USER || env.USERNAME || 'unknown';
	const capabilityId = (options.createCapabilityId || randomUUID)();
	const issueAuthorization = options.issueAuthorization || authority.issueSizeWorkflowAuthorization;
	const completeAuthorization = options.completeAuthorization || authority.completeSizeWorkflowAuthorization;
	const protectedWriter = options.writeProtectedFile || writeProtectedFile;
	const protectedRemover = options.removeProtectedFile || removeProtectedFile;
	const auditWriter = options.recordProtectedStateAuditEvent || recordProtectedStateAuditEvent;

	let authorization;
	try {
		authorization = await issueAuthorization(projectRoot, { actor, sourceHead, targetBunVersion: update.version }, { deps: options.kernelDeps, capabilityId });
	} catch (error) {
		authorization = { success: false, error: error.message };
	}
	if (!authorization.success || authorization.capabilityId !== capabilityId) {
		return { success: false, error: `Could not authorize ${SIZE_WORKFLOW_PATH}: ${authorization.error || 'authority returned a different capability id.'}` };
	}

	const writeOptions = {
		actor,
		operation: 'generate_size_workflow',
		viaForgeApi: true,
		surface: 'workflows',
		expectedContent: update.snapshot.content,
	};
	let write;
	try {
		write = protectedWriter(projectRoot, SIZE_WORKFLOW_PATH, update.content, writeOptions);
	} catch (error) {
		return { success: false, error: error.message };
	}
	if (!write.allowed) return { success: false, error: write.reason, write };

	let audit;
	try {
		audit = auditWriter(createProtectedStateAuditRecord({
			actor,
			surface: 'workflows',
			path: SIZE_WORKFLOW_PATH,
			content: update.content,
			operation: 'generate_size_workflow',
			viaForgeApi: true,
			sourceHead,
		}), { cwd: projectRoot });
	} catch (error) {
		audit = { success: false, error: error.message };
	}
	if (!audit.success) {
		const recovery = attemptRecovery(update.snapshot, projectRoot, update.content, protectedWriter, protectedRemover, writeOptions);
		return { success: false, error: `Could not record ${SIZE_WORKFLOW_PATH}: ${audit.error}`, audit, recovery };
	}

	let completion;
	try {
		completion = await completeAuthorization(projectRoot, { actor, sourceHead, capabilityId, targetBunVersion: update.version }, { deps: options.kernelDeps });
	} catch (error) {
		completion = { success: false, error: error.message };
	}
	if (!completion.success) {
		const recovery = attemptRecovery(update.snapshot, projectRoot, update.content, protectedWriter, protectedRemover, writeOptions);
		return { success: false, error: `Could not complete ${SIZE_WORKFLOW_PATH}: ${completion.error}`, audit, completion, recovery };
	}

	return {
		success: true,
		path: SIZE_WORKFLOW_PATH,
		sourceHead,
		bunVersion: update.version,
		contentHash: write.contentHash,
		write,
		audit,
		authorization,
		completion,
	};
}

module.exports = {
	SIZE_WORKFLOW_PATH,
	renderSizeWorkflow,
	readIndexedSizeWorkflow,
	resolveSizeWorkflowUpdate,
	generateSizeWorkflow,
};
