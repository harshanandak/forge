'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const {
	createProtectedStateAuditRecord,
	recordProtectedStateAuditEvent,
	removeProtectedFile,
	writeProtectedFile,
} = require('./protected-state-surfaces');
const {
	completeNpmPublishWorkflowAuthorization,
	issueNpmPublishWorkflowAuthorization,
} = require('./protected-state-authority');

const NPM_PUBLISH_WORKFLOW_PATH = '.github/workflows/npm-publish.yml';
const FULL_COMMIT_SHA = /^[0-9a-f]{40}$/;

function resolveCurrentHead(projectRoot) {
	return execFileSync('git', ['rev-parse', '--verify', 'HEAD^{commit}'], {
		cwd: projectRoot,
		encoding: 'utf8',
		stdio: ['ignore', 'pipe', 'pipe'],
		windowsHide: true,
	}).trim();
}

function verifyExpectedHead(projectRoot, expectedHead, resolveHead = resolveCurrentHead) {
	if (!expectedHead) {
		return { success: false, error: '--expect-head is required for protected workflow generation.' };
	}
	if (!FULL_COMMIT_SHA.test(expectedHead)) {
		return { success: false, error: '--expect-head must be a full 40-character lowercase commit SHA.' };
	}

	let currentHead;
	try {
		currentHead = resolveHead(projectRoot);
	} catch (error) {
		return { success: false, error: `Could not resolve current HEAD: ${error.message}` };
	}
	if (!FULL_COMMIT_SHA.test(currentHead)) {
		return { success: false, error: 'Current HEAD did not resolve to a full 40-character lowercase commit SHA.' };
	}
	if (currentHead !== expectedHead) {
		return {
			success: false,
			error: `Expected HEAD ${expectedHead} does not match current HEAD ${currentHead}.`,
		};
	}
	return { success: true, sourceHead: currentHead };
}

function renderNpmDistTagResolverScript() {
	return `CORE_RE='(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)'
NUMERIC_ID_RE='(0|[1-9][0-9]*)'
BUILD_RE='(\\+[0-9A-Za-z-]+(\\.[0-9A-Za-z-]+)*)?'
BETA_RE="^\${CORE_RE}-beta(\\.\${NUMERIC_ID_RE})*\${BUILD_RE}$"
RC_RE="^\${CORE_RE}-rc(\\.\${NUMERIC_ID_RE})*\${BUILD_RE}$"
STABLE_RE="^\${CORE_RE}\${BUILD_RE}$"

if [[ "$VERSION" =~ $BETA_RE ]]; then
  echo "tag=beta" >> "$GITHUB_OUTPUT"
elif [[ "$VERSION" =~ $RC_RE ]]; then
  echo "tag=rc" >> "$GITHUB_OUTPUT"
elif [[ "$VERSION" =~ $STABLE_RE ]]; then
  echo "tag=latest" >> "$GITHUB_OUTPUT"
elif [[ "$VERSION" == *-* ]]; then
  echo "::error::Unsupported npm prerelease: $VERSION"
  exit 1
else
  echo "::error::Invalid npm version: $VERSION"
  exit 1
fi`;
}

function snapshotWorkflow(projectRoot) {
	const fullPath = path.resolve(projectRoot, NPM_PUBLISH_WORKFLOW_PATH);
	try {
		const stat = fs.lstatSync(fullPath);
		return {
			fullPath,
			existed: true,
			content: stat.isFile() ? fs.readFileSync(fullPath) : null,
		};
	} catch (error) {
		if (error.code === 'ENOENT') return { fullPath, existed: false, content: null };
		throw error;
	}
}

function recoverWorkflow(snapshot, projectRoot, generatedContent, protectedWriter, protectedRemover, writeOptions) {
	const recoveryOptions = {
		...writeOptions,
		operation: 'recover_npm_workflow',
		expectedContent: generatedContent,
	};
	if (!snapshot.existed) {
		return protectedRemover(projectRoot, NPM_PUBLISH_WORKFLOW_PATH, recoveryOptions);
	}
	if (!Buffer.isBuffer(snapshot.content)) {
		return { allowed: false, reason: 'Previous workflow was not a regular file' };
	}
	return protectedWriter(
		projectRoot,
		NPM_PUBLISH_WORKFLOW_PATH,
		snapshot.content,
		recoveryOptions,
	);
}

function renderNpmPublishWorkflow() {
	const distTagResolver = renderNpmDistTagResolverScript()
		.split('\n')
		.map(line => line ? `          ${line}` : '')
		.join('\n');
	return `# Generated by \`forge release generate-npm-workflow\`. Do not edit directly.
name: Bun Package

on:
  release:
    types: [published]

permissions:
  contents: read

jobs:
  resolve-release:
    name: Resolve immutable release SHA
    runs-on: ubuntu-latest
    permissions:
      contents: read
    outputs:
      commitSha: \${{ steps.resolve.outputs.commitSha }}
    steps:
      - uses: actions/checkout@v7
        with:
          ref: \${{ github.event.release.tag_name }}
          fetch-depth: 0
          persist-credentials: false
      - name: Resolve release tag
        id: resolve
        shell: bash
        env:
          RELEASE_TAG: \${{ github.event.release.tag_name }}
        run: |
          set -euo pipefail
          COMMIT_SHA="$(git rev-parse "\${RELEASE_TAG}^{commit}")"
          if [ -z "$COMMIT_SHA" ] || [ "$COMMIT_SHA" != "$(git rev-parse HEAD)" ]; then
            echo "::error::Release tag did not resolve to the checked out commit"
            exit 1
          fi
          echo "commitSha=$COMMIT_SHA" >> "$GITHUB_OUTPUT"

  build:
    needs: resolve-release
    runs-on: ubuntu-latest
    permissions:
      contents: read
    outputs:
      commitSha: \${{ steps.evidence.outputs.commitSha }}
      receipt: \${{ steps.evidence.outputs.receipt }}
      receiptSubject: \${{ steps.evidence.outputs.receiptSubject }}
    steps:
      - uses: actions/checkout@v7
        with:
          ref: \${{ needs.resolve-release.outputs.commitSha }}
          fetch-depth: 1
          persist-credentials: false
      - uses: actions/setup-node@v7
        with:
          node-version: 22
      - uses: oven-sh/setup-bun@v2
        with:
          bun-version: 1.3.12
      - run: bun install --frozen-lockfile
      - name: Setup test fixtures
        shell: bash
        run: bash test-env/automation/setup-fixtures.sh --force
      - name: Run complete release suite
        shell: bash
        run: |
          set -euo pipefail
          node scripts/test-full-suite.js --label-prefix release-full
      - name: Emit attributable release suite receipt
        id: evidence
        env:
          EXPECTED_SHA: \${{ needs.resolve-release.outputs.commitSha }}
        run: node scripts/npm-release-receipt.js emit

  publish-npm:
    needs: [resolve-release, build]
    runs-on: ubuntu-latest
    permissions:
      contents: read
      id-token: write
    steps:
      - uses: actions/checkout@v7
        with:
          ref: \${{ needs.resolve-release.outputs.commitSha }}
          fetch-depth: 1
          persist-credentials: false
      - uses: actions/setup-node@v7
        with:
          node-version: 22
          registry-url: https://registry.npmjs.org/
      - name: Verify exact release suite receipt
        env:
          EXPECTED_SHA: \${{ needs.resolve-release.outputs.commitSha }}
          VERIFIED_SHA: \${{ needs.build.outputs.commitSha }}
          RECEIPT: \${{ needs.build.outputs.receipt }}
          RECEIPT_SUBJECT: \${{ needs.build.outputs.receiptSubject }}
        run: node scripts/npm-release-receipt.js verify
      - uses: oven-sh/setup-bun@v2
        with:
          bun-version: 1.3.12
      - run: bun install --frozen-lockfile
      - name: Release tag matches package.json version
        shell: bash
        run: |
          set -euo pipefail
          PKG="$(node -p "require('./package.json').version")"
          TAG="\${GITHUB_REF_NAME#v}"
          if [ "$PKG" != "$TAG" ]; then
            echo "::error::Release tag ($TAG) != package.json version ($PKG). Bump package.json before releasing."
            exit 1
          fi
      - name: Release-readiness gate
        run: node bin/forge.js release check --target "$(node -p "require('./package.json').version.split('-')[0]")"
      - name: Verify package contents
        run: npm pack --dry-run
      - name: Ensure OIDC-capable npm
        run: npm install --global npm@11.5.1 && npm --version
      - name: Resolve npm dist-tag
        id: dist-tag
        shell: bash
        run: |
          set -euo pipefail
          VERSION="$(node -p "require('./package.json').version")"
${distTagResolver}
      - name: Publish to npm
        shell: bash
        run: |
          set -euo pipefail
          DIST_TAG="\${{ steps.dist-tag.outputs.tag }}"
          case "$DIST_TAG" in
            beta)
              npm publish --provenance --tag beta
              ;;
            rc)
              npm publish --provenance --tag rc
              ;;
            latest)
              npm publish --provenance
              ;;
            *)
              echo "::error::Unsupported npm dist-tag: $DIST_TAG"
              exit 1
              ;;
          esac
`;
}

async function generateNpmPublishWorkflow(projectRoot, options = {}) {
	const head = verifyExpectedHead(projectRoot, options.expectedHead, options.resolveHead);
	if (!head.success) return head;
	const sourceHead = head.sourceHead;
	const content = renderNpmPublishWorkflow();
	const actor = options.actor || options.env?.FORGE_ACTOR || process.env.FORGE_ACTOR || process.env.USER || process.env.USERNAME || 'unknown';
	const protectedWriter = options.writeProtectedFile || writeProtectedFile;
	const protectedRemover = options.removeProtectedFile || removeProtectedFile;
	const auditWriter = options.recordProtectedStateAuditEvent || recordProtectedStateAuditEvent;
	const prepareAuthorization = options.prepareNpmPublishWorkflowAuthorization || issueNpmPublishWorkflowAuthorization;
	const activateAuthorization = options.activateNpmPublishWorkflowAuthorization || completeNpmPublishWorkflowAuthorization;
	const snapshot = snapshotWorkflow(projectRoot);
	const writeOptions = {
		actor,
		operation: 'generate_npm_workflow',
		viaForgeApi: true,
		surface: 'workflows',
	};
	let trustedAuthorization;
	try {
		trustedAuthorization = await prepareAuthorization(
			projectRoot,
			{ actor, sourceHead },
			{ deps: options.kernelDeps },
		);
	} catch (error) {
		trustedAuthorization = { success: false, error: error.message };
	}
	if (!trustedAuthorization.success) {
		return {
			success: false,
			error: `Could not record trusted protected-state authorization: ${trustedAuthorization.error}`,
			trustedAuthorization,
		};
	}

	let write;
	try {
		write = protectedWriter(projectRoot, NPM_PUBLISH_WORKFLOW_PATH, content, {
			...writeOptions,
			...(options.beforeAtomicCommit ? { beforeAtomicCommit: options.beforeAtomicCommit } : {}),
		});
	} catch (error) {
		return { success: false, error: error.message };
	}
	if (!write.allowed) {
		return { success: false, error: write.reason, write };
	}

	const auditRecord = createProtectedStateAuditRecord({
		actor,
		surface: 'workflows',
		path: NPM_PUBLISH_WORKFLOW_PATH,
		content,
		operation: 'generate_npm_workflow',
		viaForgeApi: true,
		sourceHead,
	});
	let audit;
	try {
		audit = auditWriter(auditRecord, { cwd: projectRoot });
	} catch (error) {
		audit = { success: false, error: error.message };
	}
	if (!audit.success) {
		let recovery;
		try {
			recovery = recoverWorkflow(snapshot, projectRoot, content, protectedWriter, protectedRemover, writeOptions);
		} catch (error) {
			recovery = { allowed: false, reason: error.message };
		}
		return {
			success: false,
			error: `Could not record protected-state authorization: ${audit.error}`,
			audit,
			recovery,
		};
	}

	let writeCompletion;
	try {
		writeCompletion = await activateAuthorization(
			projectRoot,
			{ actor, sourceHead, capabilityId: trustedAuthorization.capabilityId },
			{ deps: options.kernelDeps },
		);
	} catch (error) {
		writeCompletion = { success: false, error: error.message };
	}
	if (!writeCompletion.success) {
		let recovery;
		try {
			recovery = recoverWorkflow(snapshot, projectRoot, content, protectedWriter, protectedRemover, writeOptions);
		} catch (error) {
			recovery = { allowed: false, reason: error.message };
		}
		return {
			success: false,
			error: `Could not complete trusted protected-state authorization: ${writeCompletion.error}`,
			audit,
			trustedAuthorization,
			writeCompletion,
			recovery,
		};
	}

	return {
		success: true,
		path: NPM_PUBLISH_WORKFLOW_PATH,
		sourceHead,
		contentHash: write.contentHash,
		write,
		audit,
		trustedAuthorization,
		writeCompletion,
	};
}

module.exports = {
	NPM_PUBLISH_WORKFLOW_PATH,
	renderNpmDistTagResolverScript,
	renderNpmPublishWorkflow,
	verifyExpectedHead,
	generateNpmPublishWorkflow,
};
